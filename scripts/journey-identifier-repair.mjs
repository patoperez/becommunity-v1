// =============================================================================
// Realign a study's journey stage identifiers with the stages they name.
//
//   npx tsx scripts/journey-identifier-repair.mjs --study <uuid> [--confirm]
//     (needs NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY)
// =============================================================================
// A stage id is a STABLE OPAQUE IDENTIFIER. Studio derives it from the label
// once, when the stage is created, and never regenerates it — renaming a moment
// must not orphan the observations whose `confirmed_stage_key` points at it. An
// id that no longer reads like its label is therefore NORMAL after a rename and
// is not, by itself, a defect.
//
// It IS a defect when the ids were never generated by the product at all. The
// real Cuicuilco journey was written by an external script and its ids sit one
// position out of step with the labels and metrics they belong to: the stage
// labelled "Reuniones uno a uno" carries the id `dar_referencias`, which is the
// id the product itself would have given the PREVIOUS stage. The client-visible
// label and metric are correct; the internal identifier names the wrong thing,
// and the next person to read it will be misled.
//
// This repairs that, and refuses to do so blindly:
//
//   - it only proposes the id the product's own generator would produce;
//   - it REFUSES if any observation in the study carries a confirmed stage key,
//     because renaming an id that something points at is data loss;
//   - it REFUSES if an interpretation references a journey stage;
//   - it changes nothing else in the journey — labels, metrics, order and
//     descriptions are written back exactly as they were;
//   - it is idempotent: a second run finds nothing to do.
// =============================================================================

import { writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { createClient } from "@supabase/supabase-js";
import { stageIdFromLabel } from "../src/lib/studio/journey-picker.ts";
import { parseJourneyDefinition } from "../src/lib/calc/journey.ts";

const arg = (name) => {
  const at = process.argv.indexOf("--" + name);
  return at === -1 ? null : process.argv[at + 1] ?? null;
};
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const studyId = arg("study");
const backupDir = arg("backup-dir");
const confirm = process.argv.includes("--confirm");
if (!UUID.test(studyId ?? "")) {
  console.error("Usage: --study <uuid> --backup-dir <path outside the repo> [--confirm]");
  process.exit(2);
}
if (confirm && !backupDir) {
  console.error("--backup-dir is required with --confirm: the previous journey must be recoverable.");
  process.exit(2);
}
// A backup of real study configuration must not land where git can see it.
// The test is containment in the working tree, not a name: a scratch directory
// may legitimately carry the project name in its path.
if (backupDir && resolve(backupDir).startsWith(resolve(process.cwd()))) {
  console.error("Refusing to write a backup inside the repository. Choose a path outside it.");
  process.exit(2);
}
const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key) {
  console.error("NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY must be set.");
  process.exit(2);
}
const admin = createClient(url, key, { auth: { persistSession: false } });

const { data: study, error } = await admin
  .from("study").select("id, name, status, journey_definition").eq("id", studyId).maybeSingle();
if (error || !study) {
  console.error("Study not found: " + (error?.message ?? studyId));
  process.exit(1);
}
const stages = parseJourneyDefinition(study.journey_definition);
if (stages.length === 0) {
  console.log("This study has no journey. Nothing to do.");
  process.exit(0);
}

console.log("=".repeat(70));
console.log("Journey identifier repair");
console.log("=".repeat(70));
console.log("study  " + study.name + " (" + study.id + ")  status " + study.status);

// ---- What the product's own generator would produce -------------------------
const taken = new Set();
const proposals = stages.map((stage, index) => {
  const proposed = stageIdFromLabel(stage.label, taken, index + 1);
  taken.add(proposed);
  return { stage, proposed, drifted: proposed !== stage.id };
});

console.log("\nSTAGE                          CURRENT ID                     PROPOSED ID");
for (const { stage, proposed, drifted } of proposals) {
  console.log(
    "  " + stage.label.padEnd(29).slice(0, 29) +
      " " + stage.id.padEnd(29).slice(0, 29) +
      " " + (drifted ? proposed : "(unchanged)"),
  );
}
const drifted = proposals.filter((p) => p.drifted);
console.log("\n" + drifted.length + " of " + stages.length + " identifier(s) do not match their label.");
if (drifted.length === 0) process.exit(0);

// ---- Refuse if anything points at these ids ---------------------------------
const { count: taggedCount, error: taggedError } = await admin
  .from("qual_observation").select("id", { count: "exact", head: true })
  .eq("study_id", studyId).not("confirmed_stage_key", "is", null);
if (taggedError) {
  console.error("Could not check observations: " + taggedError.message);
  process.exit(1);
}
console.log("observations carrying a confirmed stage key: " + (taggedCount ?? 0));
if ((taggedCount ?? 0) > 0) {
  console.error(
    "\nREFUSING. Observations point at these identifiers. Renaming one would orphan\n" +
      "them, and a stage id is deliberately stable across a rename for exactly that\n" +
      "reason. Leave the identifiers alone and record why in the study runbook.",
  );
  process.exit(1);
}

// migration 0017: one row per study, keyed by study_id, with a draft and a
// published document. BOTH are checked — a draft that cites a stage would be
// silently rewritten by a rename just as a published one would.
const { data: interpretations, error: interpretationError } = await admin
  .from("study_interpretation")
  .select("study_id, review_status, draft_content, published_content")
  .eq("study_id", studyId);
if (interpretationError) {
  console.error("Could not check interpretations: " + interpretationError.message);
  process.exit(1);
}
const referencing = (interpretations ?? []).filter((r) => {
  const text = JSON.stringify(r.draft_content ?? {}) + JSON.stringify(r.published_content ?? {});
  return stages.some((stage) => text.includes("journey:" + stage.id));
});
console.log("interpretations referencing a stage: " + referencing.length);
if (referencing.length > 0) {
  console.error("\nREFUSING. An interpretation cites one of these stages as evidence.");
  process.exit(1);
}

if (!confirm) {
  console.log("\nDRY RUN. Re-run with --confirm to write the realigned identifiers.");
  process.exit(0);
}

// ---- Back up the configuration this replaces --------------------------------
// The journey definition only. No respondent, no answer, no quote.
if (!existsSync(backupDir)) mkdirSync(backupDir, { recursive: true });
const stamp = new Date().toISOString().replaceAll(":", "-").slice(0, 19);
const backupPath = join(backupDir, "journey-definition-" + studyId + "-" + stamp + ".json");
writeFileSync(
  backupPath,
  JSON.stringify({ study_id: studyId, captured_at: new Date().toISOString(), journey_definition: study.journey_definition }, null, 2),
);
console.log("");
console.log("Backup of the previous journey: " + backupPath);

// ---- Write back, changing only the ids --------------------------------------
const repaired = {
  stages: proposals.map(({ stage, proposed }) => ({
    id: proposed,
    label: stage.label,
    metric: stage.metric,
    ...(stage.description ? { description: stage.description } : {}),
  })),
};
// Prove the result is still a valid journey BEFORE writing it.
if (parseJourneyDefinition(repaired).length !== stages.length) {
  console.error("REFUSING: the repaired journey does not parse. Nothing was written.");
  process.exit(1);
}

const { error: writeError } = await admin
  .from("study").update({ journey_definition: repaired }).eq("id", studyId);
if (writeError) {
  console.error("Write failed: " + writeError.message);
  process.exit(1);
}

const { data: after } = await admin.from("study").select("journey_definition").eq("id", studyId).maybeSingle();
const verified = parseJourneyDefinition(after?.journey_definition);
console.log("\nAFTER");
for (const stage of verified) console.log("  " + stage.id.padEnd(30) + stage.label + "  ->  " + stage.metric);
const stillDrifted = verified.filter((stage, index) => {
  const seen = new Set(verified.slice(0, index).map((s) => s.id));
  return stageIdFromLabel(stage.label, seen, index + 1) !== stage.id;
});
console.log("\nidentifiers still out of step: " + stillDrifted.length);
process.exit(stillDrifted.length === 0 ? 0 : 1);
