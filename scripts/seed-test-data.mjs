// =============================================================================
// Seed two isolated test tenants + users + data using the SERVICE_ROLE key.
// =============================================================================
// This runs server-side only (service_role bypasses RLS, §6.3) to provision the
// fixtures the behavioral isolation test needs (§6.5). It is idempotent: safe to
// re-run. After it finishes it appends TEST_* vars to .env.local so
// `node --env-file=.env.local scripts/isolation-test.mjs` works.
//
//   node --env-file=.env.local scripts/seed-test-data.mjs
// =============================================================================

import { createClient } from "@supabase/supabase-js";
import { readFileSync, writeFileSync } from "node:fs";

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const serviceRole = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!url || !serviceRole || url.includes("__FILL_ME__")) {
  console.error(
    "Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY in .env.local",
  );
  process.exit(2);
}

const admin = createClient(url, serviceRole, {
  auth: { autoRefreshToken: false, persistSession: false },
});

const USERS = {
  A: { email: "test-tenant-a@becommunity.test", password: "Test-A-pass-2026!", tenant: "Colegio Alfa (TEST A)" },
  B: { email: "test-tenant-b@becommunity.test", password: "Test-B-pass-2026!", tenant: "Colegio Beta (TEST B)" },
  INTERNAL: { email: "test-internal@becommunity.test", password: "Test-Int-pass-2026!" },
};

async function upsertTenant(name) {
  const { data: existing } = await admin
    .from("tenant").select("id").eq("name", name).maybeSingle();
  if (existing) return existing.id;
  const { data, error } = await admin
    .from("tenant").insert({ name }).select("id").single();
  if (error) throw new Error(`tenant insert failed: ${error.message}`);
  return data.id;
}

async function upsertUser(email, password) {
  // Find existing user by listing (admin API has no get-by-email).
  let page = 1;
  for (;;) {
    const { data, error } = await admin.auth.admin.listUsers({ page, perPage: 200 });
    if (error) throw new Error(`listUsers failed: ${error.message}`);
    const found = data.users.find((u) => u.email === email);
    if (found) return found.id;
    if (data.users.length < 200) break;
    page += 1;
  }
  const { data, error } = await admin.auth.admin.createUser({
    email, password, email_confirm: true,
  });
  if (error) throw new Error(`createUser failed: ${error.message}`);
  return data.user.id;
}

async function upsertProfile(userId, tenantId, role = "client") {
  const { error } = await admin
    .from("profiles")
    .upsert({ user_id: userId, tenant_id: tenantId, role }, { onConflict: "user_id" });
  if (error) throw new Error(`profile upsert failed: ${error.message}`);
}

async function seedStudyData(tenantId) {
  const { data: existing } = await admin
    .from("study").select("id").eq("tenant_id", tenantId).limit(1).maybeSingle();
  if (existing) return existing.id;

  const { data: study, error } = await admin
    .from("study")
    .insert({ tenant_id: tenantId, name: "Satisfacción 2026 (TEST)", period: "2026", status: "draft" })
    .select("id").single();
  if (error) throw new Error(`study insert failed: ${error.message}`);

  const { data: respondent } = await admin
    .from("respondent")
    .insert({ tenant_id: tenantId, study_id: study.id, segments: { genero: "F", nivel: "preescolar" } })
    .select("id").single();

  await admin.from("quant_response").insert({
    tenant_id: tenantId, study_id: study.id, respondent_id: respondent.id,
    metric_key: "sat_maestros", value: 8,
  });
  await admin.from("qual_observation").insert({
    tenant_id: tenantId, study_id: study.id, respondent_id: respondent.id,
    source: "encuesta", category: "maestros", theme: "trato", quote: "Excelente atención.",
  });
  return study.id;
}

function writeTestEnv(vars) {
  const path = ".env.local";
  let content = readFileSync(path, "utf8").replace(/\n# --- TEST FIXTURES[\s\S]*$/, "");
  const block =
    "\n# --- TEST FIXTURES (generated by seed-test-data.mjs; gitignored) ---\n" +
    Object.entries(vars).map(([k, v]) => `${k}=${v}`).join("\n") + "\n";
  writeFileSync(path, content.trimEnd() + "\n" + block);
  console.log("Wrote TEST_* fixtures to .env.local");
}

async function main() {
  const tenantA = await upsertTenant(USERS.A.tenant);
  const tenantB = await upsertTenant(USERS.B.tenant);

  const userA = await upsertUser(USERS.A.email, USERS.A.password);
  const userB = await upsertUser(USERS.B.email, USERS.B.password);
  const userInternal = await upsertUser(USERS.INTERNAL.email, USERS.INTERNAL.password);

  await upsertProfile(userA, tenantA);
  await upsertProfile(userB, tenantB);
  // Internal Be Community user: role 'internal', NO tenant (§7.1). Data access
  // is governed by role on the server (service_role), not by RLS membership.
  await upsertProfile(userInternal, null, "internal");

  await seedStudyData(tenantA);
  await seedStudyData(tenantB);

  console.log("Seed complete:");
  console.log("  Tenant A:", tenantA, "->", USERS.A.email);
  console.log("  Tenant B:", tenantB, "->", USERS.B.email);
  console.log("  Internal:", USERS.INTERNAL.email);

  writeTestEnv({
    TEST_USER_A_EMAIL: USERS.A.email,
    TEST_USER_A_PASSWORD: USERS.A.password,
    TEST_USER_B_EMAIL: USERS.B.email,
    TEST_USER_B_PASSWORD: USERS.B.password,
    TEST_TENANT_B_ID: tenantB,
    TEST_TENANT_A_ID: tenantA,
    TEST_INTERNAL_EMAIL: USERS.INTERNAL.email,
    TEST_INTERNAL_PASSWORD: USERS.INTERNAL.password,
  });
}

main().catch((e) => { console.error("Seed failed:", e.message); process.exit(1); });
